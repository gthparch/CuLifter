// Microbenchmark: cub block-level match-based radix ranking, isolated from
// DeviceRadixSortOnesweepKernel (HeCBench sa-cuda / sortKV-cuda blocker).
//
// Instantiates the SAME ranking family the Onesweep agent uses on sm_90:
//   BlockRadixRankMatchEarlyCounts<BLOCK_THREADS, RADIX_BITS, false,
//                                  BLOCK_SCAN_WARP_SCANS, WARP_MATCH_ANY>
// (cub/agent/agent_radix_sort_onesweep.cuh selects this when RANK_ALGORITHM
//  == RADIX_RANK_MATCH_EARLY_COUNTS_ANY, the default Onesweep policy).
//
// The instruction under test is ATOMS.POPC.INC.32 (warp-aggregated shared
// increment, generated by ptxas from atomicAdd(&warp_histograms[digit], 1))
// plus the leader-only ATOMS.ADD in ComputeRanksItem. ptxas emits NO
// WARPSYNC between the histogram zero-init STS loop and the increments —
// ordering relies on physical warp lockstep.
#include <cstdint>
#include <cub/block/block_radix_rank.cuh>

#ifndef BT
#define BT 384  // BLOCK_THREADS, matches Onesweep __launch_bounds__
#endif
#define IPT 4   // keys per thread (small; Onesweep uses ~17)
#define RB 8    // RADIX_BITS, matches Onesweep
#define TILE (BT * IPT)

struct LowByteExtractor {
  __device__ __forceinline__ int Digit(uint32_t key) { return key & 0xFF; }
};

using RankT = cub::BlockRadixRankMatchEarlyCounts<
    BT, RB, false, cub::BLOCK_SCAN_WARP_SCANS, cub::WARP_MATCH_ANY>;

extern "C" __global__ void __launch_bounds__(BT)
rank_kernel(const uint32_t* in, int* ranks_out, int* digits_out) {
  __shared__ typename RankT::TempStorage tmp;
  uint32_t keys[IPT];
  int ranks[IPT];
#pragma unroll
  for (int u = 0; u < IPT; ++u) keys[u] = in[u * BT + threadIdx.x];
  int exclusive_prefix[RankT::BINS_PER_THREAD];
  RankT(tmp).RankKeys(keys, ranks, LowByteExtractor{}, exclusive_prefix);
#pragma unroll
  for (int u = 0; u < IPT; ++u) {
    ranks_out[u * BT + threadIdx.x] = ranks[u];
    digits_out[u * BT + threadIdx.x] = (int)(keys[u] & 0xFF);
  }
}
