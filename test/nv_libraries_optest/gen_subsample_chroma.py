#!/usr/bin/env python3
# gen_subsample_chroma.py — generate x86 exec-correctness harnesses for all
# nvjpeg::subsample_chroma_kernel<srcSub,dstSub,LaunchParams<32,8>> variants.
#
# Kernel (decoded from SASS, libnvjpeg sm_90 nvjpeg.cubin):
#   void subsample_chroma_kernel<(CSS)src,(CSS)dst,LP<32,8>>(
#       nvjpegImage_t in, NppiSize inSize, nvjpegImage_t out, NppiSize roi)
#   Resamples Cb(ch1) and Cr(ch2) planes; Y(ch0) untouched. Grid covers OUTPUT
#   (dst) chroma dims = roi. inSize = SRC chroma dims (clamps src reads, replicate
#   edge). Per output (r,c):
#     - horizontal: if Hd>=Hs (downsample/equal): hbox=Hd//Hs, src cols = c*hbox..+hbox-1
#                   else (upsample):              hbox=1,       src col  = c // (Hs//Hd)
#     - vertical:   analogous with Vd,Vs
#     - out = floor( sum(src over hbox x vbox block, edge-clamped) / (hbox*vbox) )
#   Value path: integer sum -> I2FP.F32 -> FMUL by 1/(hbox*vbox) -> FMNMX[0,255]
#   -> F2I.U32.TRUNC. Bit-exact integer divide for the averaged value.
#
# const-bank: in.ch1@0x218 ch2@0x220, in.pitchCb@0x238 pitchCr@0x240,
#   inSize.w@0x250 h@0x254, out.ch1@0x260 ch2@0x268, out.pitchCb@0x280 pitchCr@0x288,
#   roi.w@0x298 h@0x29C.
import os, sys

# (H,V) chroma decimation factor per nvjpegChromaSubsampling_t enum value.
FAC  = {0:(1,1), 1:(2,1), 2:(2,2), 3:(1,2), 4:(4,1), 5:(4,2)}
NAME = {0:'444', 1:'422', 2:'420', 3:'440', 4:'411', 5:'410'}

ROOT = os.path.dirname(os.path.abspath(__file__))

def mangled(s, d):
    return (f"_ZN6nvjpeg23subsample_chroma_kernelIL25nvjpegChromaSubsampling_t{s}E"
            f"LS1_{d}ENS_20SampleChromaDispatch12LaunchParamsILi32ELi8EEEEEv"
            f"13nvjpegImage_t8NppiSizeS5_S6_")

def factors(s, d):
    Hs,Vs = FAC[s]; Hd,Vd = FAC[d]
    hbox = Hd//Hs if Hd>=Hs else 1
    vbox = Vd//Vs if Vd>=Vs else 1
    hup  = Hs//Hd if Hs>Hd else 1
    vup  = Vs//Vd if Vs>Vd else 1
    return hbox, vbox, hup, vup

def dims(s, d, SW, SH):
    """dst chroma dims from src chroma dims SW,SH and the H/V factor change.
       dst_w = SW * Hs/Hd, dst_h = SH * Vs/Vd."""
    Hs,Vs = FAC[s]; Hd,Vd = FAC[d]
    DW = SW * Hs // Hd
    DH = SH * Vs // Vd
    return DW, DH

HOST_TMPL = r'''// host_cpu.cpp (generated by gen_subsample_chroma.py)
// nvjpeg::subsample_chroma_kernel<(CSS){s} /*{ns}*/, (CSS){d} /*{nd}*/, LP<32,8>>
// Resamples Cb/Cr {ns}->{nd}.  hbox={hbox} vbox={vbox} hup={hup} vup={vup} div={div}.
//   out(r,c) = floor( sum(src[clamp(sr)][clamp(sc)] over {hbox}x{vbox} block) / {div} )
//   src col: {hcomment}   src row: {vcomment}
#include <cstdint>
#include <cstdio>
#include "kernel_wrapper.h"
#include "nvlib_compare.h"

extern "C" void {mg}();

static inline int clampc(int v, int hi) {{ return v < 0 ? 0 : (v > hi ? hi : v); }}

int main() {{
    constexpr int SW = {SW}, SH = {SH};   // src chroma plane dims
    constexpr int DW = {DW}, DH = {DH};   // dst chroma plane dims
    constexpr int hbox = {hbox}, vbox = {vbox}, hup = {hup}, vup = {vup}, DIV = {div};
    uint8_t srcCb[SH*SW], srcCr[SH*SW];
    uint8_t dstCb[DH*DW], dstCr[DH*DW];
    uint8_t refCb[DH*DW], refCr[DH*DW];

    // High-frequency, non-separable input so box geometry (size + which pixels)
    // is genuinely discriminating: a wrong block shape gives a different average.
    auto hashb = [](int r, int c, int salt) -> uint8_t {{
        unsigned x = (unsigned)(r*73856093) ^ (unsigned)(c*19349663) ^ (unsigned)(salt*83492791);
        x ^= x >> 13; x *= 2654435761u; x ^= x >> 16;
        return (uint8_t)(x & 0xFF);
    }};
    for (int r = 0; r < SH; ++r) for (int c = 0; c < SW; ++c) {{
        srcCb[r*SW+c] = hashb(r, c, 1);
        srcCr[r*SW+c] = hashb(r, c, 2);
    }}
    // Independent reference, decoded straight from SASS semantics.
    for (int r = 0; r < DH; ++r) for (int c = 0; c < DW; ++c) {{
        int sc0 = (hbox >= 1 && hup == 1) ? c*hbox : c/hup;   // downsample start vs upsample (replicate)
        int sr0 = (vbox >= 1 && vup == 1) ? r*vbox : r/vup;
        int sumCb = 0, sumCr = 0;
        for (int dy = 0; dy < vbox; ++dy) for (int dx = 0; dx < hbox; ++dx) {{
            int sr = clampc(sr0 + dy, SH-1), sc = clampc(sc0 + dx, SW-1);
            sumCb += srcCb[sr*SW+sc];
            sumCr += srcCr[sr*SW+sc];
        }}
        // I2FP -> *(1/DIV) -> clamp[0,255] -> truncate. For DIV>=1 exact ints,
        // floor(sum/DIV) == integer sum/DIV.
        int vCb = sumCb / DIV; if (vCb > 255) vCb = 255; if (vCb < 0) vCb = 0;
        int vCr = sumCr / DIV; if (vCr > 255) vCr = 255; if (vCr < 0) vCr = 0;
        refCb[r*DW+c] = (uint8_t)vCb;
        refCr[r*DW+c] = (uint8_t)vCr;
    }}
    for (int i = 0; i < DH*DW; ++i) {{ dstCb[i] = dstCr[i] = 0xCC; }}

    launchKernel2D({mg},
        Dim3{{(DW+31)/32,(DH+7)/8}}, Dim3{{32,8}},
        ArgAt{{0x218}}, (uint8_t*)srcCb, ArgAt{{0x220}}, (uint8_t*)srcCr,
        ArgAt{{0x238}}, (uint64_t)SW,    ArgAt{{0x240}}, (uint64_t)SW,
        ArgAt{{0x250}}, (int)SW,         ArgAt{{0x254}}, (int)SH,
        ArgAt{{0x260}}, (uint8_t*)dstCb, ArgAt{{0x268}}, (uint8_t*)dstCr,
        ArgAt{{0x280}}, (uint64_t)DW,    ArgAt{{0x288}}, (uint64_t)DW,
        ArgAt{{0x298}}, (int)DW,         ArgAt{{0x29C}}, (int)DH);

    // DIV>1 => value derived through FP; allow +/-1 ULP. DIV==1 => pure data move, exact.
    long tol = (DIV > 1) ? 1 : 0;
    int bad = cmp_u8_tol(dstCb, refCb, DH*DW, tol, "Cb")
            + cmp_u8_tol(dstCr, refCr, DH*DW, tol, "Cr");
    printf("=== {ns}->{nd}: DW=%d DH=%d div=%d  dstCb[0]=%u ref=%u  dstCr[0]=%u ref=%u ===\n",
           DW,DH,DIV,dstCb[0],refCb[0],dstCr[0],refCr[0]);
    return report(bad, 2*DH*DW);
}}
'''

def main():
    # base src chroma dims: multiple of 8 (covers hup/vup up to 4 cleanly, >32 wide
    # to exercise multiple CTAs in x; even small enough to run fast).
    BASE_SW, BASE_SH = 48, 24
    for s in range(6):
        for d in range(6):
            hbox,vbox,hup,vup = factors(s,d)
            div = hbox*vbox
            # ensure src dims divisible by hbox/vbox (downsample) AND that dst dims
            # are positive integers under upsample. BASE 48x24 divisible by 1,2,4.
            SW, SH = BASE_SW, BASE_SH
            DW, DH = dims(s,d,SW,SH)
            tdir = os.path.join(ROOT, f"subsample_chroma_s{s}_d{d}")
            os.makedirs(tdir, exist_ok=True)
            hcomment = (f"c*{hbox} (downsample)" if hup==1 else f"c/{hup} (upsample replicate)")
            vcomment = (f"r*{vbox} (downsample)" if vup==1 else f"r/{vup} (upsample replicate)")
            src = HOST_TMPL.format(
                s=s,d=d,ns=NAME[s],nd=NAME[d],mg=mangled(s,d),
                SW=SW,SH=SH,DW=DW,DH=DH,
                hbox=hbox,vbox=vbox,hup=hup,vup=vup,div=div,
                hcomment=hcomment,vcomment=vcomment)
            with open(os.path.join(tdir,"host_cpu.cpp"),"w") as f:
                f.write(src)
            rule = (f"out(r,c)=floor( sum(src over {hbox}x{vbox} block, edge-clamped to "
                    f"src dims) / {div} ); src col {'='+str(hbox)+'*c (downsample)' if hup==1 else '=c//'+str(hup)+' (upsample replicate)'}; "
                    f"src row {'='+str(vbox)+'*r (downsample)' if vup==1 else '=r//'+str(vup)+' (upsample replicate)'}")
            meta = {
                "name": f"subsample_chroma_s{s}_d{d}",
                "desc": (f"nvjpeg::subsample_chroma_kernel<(CSS){s}={NAME[s]},(CSS){d}={NAME[d]},"
                         f"LaunchParams<32,8>> from libnvjpeg sm_90 nvjpeg.cubin. Resamples the "
                         f"Cb(ch1)/Cr(ch2) chroma planes from {NAME[s]} to {NAME[d]} subsampling "
                         f"(Y/ch0 untouched). Grid covers OUTPUT chroma dims (roi@0x298). inSize@0x250 "
                         f"= SRC chroma dims (clamps source reads, replicate edge). Resampling rule: "
                         f"{rule}. Value path: integer block-sum -> I2FP.F32 -> FMUL*(1/{div}) -> "
                         f"FMNMX[0,255] -> F2I.U32.TRUNC. Independent host reference decoded from SASS; "
                         f"high-frequency non-separable input makes the box geometry discriminating. "
                         f"const-bank: in.ch1@0x218 ch2@0x220 pitch@0x238/40, inSize@0x250, "
                         f"out.ch1@0x260 ch2@0x268 pitch@0x280/88, roi@0x298."),
                "tags": ["sm90","nv_libraries","nvjpeg","chroma_subsampling","resample",
                         "execution_correctness","cpu_x86","planar",
                         ("downsample" if (hbox>1 or vbox>1) else ("upsample" if (hup>1 or vup>1) else "copy"))],
                "kernel_func": mangled(s,d),
                "source_cubin": "benchmark/nv_libraries/cubins/nvjpeg.cubin",
                "native_arch": "sm90",
                "ground_truth": "x86-lifted vs independent host reference: 0 mismatches, TEST PASSED",
            }
            import json
            with open(os.path.join(tdir,"metadata.json"),"w") as f:
                json.dump(meta, f, indent=2)
    print("generated 36 host_cpu.cpp + metadata.json")

if __name__ == "__main__":
    main()
